/**
 * 표기 흔들림을 걷어내고 대표값 하나로 수렴시킵니다.
 * 반환값이 빈 문자열이면 facet으로 쓸 수 없는 값이라는 뜻입니다.
 */
export function canonicalize(raw: string): string {
  if (!raw) return '';

  let value = raw.trim();

  // 괄호 보충 설명 제거: '둔근(엉덩이)' -> '둔근'
  value = value.replace(/\s*[（(][^)）]*[)）]\s*/g, ' ').trim();

  // 슬래시로 대안을 나열한 경우 첫 항목만 씁니다: '깨소금 / 숟가락' -> '깨소금'
  value = value.split('/')[0];

  // 수량 표현 제거: '감자 2개' -> '감자'
  // 단위 뒤에 분수(1/2)나 물결(2~3)이 붙는 경우까지 함께 걷어냅니다.
  value = value.replace(new RegExp(`[\\d./~]+\\s*(${UNIT_PATTERN})?`, 'g'), ' ');

  // 수량이 사라지고 단위만 남는 경우가 많습니다: '베이컨 2줄' -> '베이컨 줄' -> '베이컨'
  value = value.replace(new RegExp(`(^|\\s)(${UNIT_PATTERN})(?=\\s|$)`, 'g'), ' ');

  // 수식어 제거
  for (const noise of MEASURE_NOISE) {
    value = value.replace(new RegExp(noise, 'g'), ' ');
  }

  value = value.replace(/\s+/g, ' ').trim();

  // 너무 짧거나 기호만 남은 값은 버립니다.
  if (value.length < 1 || !/[가-힣a-zA-Z0-9]/.test(value)) return '';

  const aliased = ALIASES[value];
  return aliased ?? value;
}

/**
 * 값 하나를 상위 개념까지 펼칩니다. 자기 자신이 항상 첫 원소입니다.
 * 예) '강릉' -> ['강릉', '강원도', '국내']
 */
export function expand(value: string): string[] {
  const result: string[] = [];
  const seen = new Set<string>();

  let current: string | undefined = value;
  // 사전에 순환이 생겨도 무한 루프에 빠지지 않도록 방문 여부로 끊습니다.
  while (current && !seen.has(current)) {
    seen.add(current);
    result.push(current);
    current = PARENTS[current];
  }

  return result;
}

/** 원본 문자열을 정규화 + 계층 확장까지 한 번에 처리합니다. */
export function normalizeToValues(raw: string): string[] {
  const canonical = canonicalize(raw);
  if (!canonical) return [];
  return expand(canonical);
}


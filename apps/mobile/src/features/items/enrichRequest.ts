/**
 * 한 번의 정리 작업 전체에 붙는 이름표.
 *
 * 정리 한 건은 바깥 호출을 여러 번 합니다(링크 본문 읽기 + AI 호출). 그 과정에서
 * 앱이 죽으면 다시 켰을 때 회수가 처음부터 다시 돌리는데, 지금은 서버가 그것을
 * 새 요청과 구별할 방법이 없어서 같은 요약을 두 번 삽니다.
 *
 * 앱이 죽는 일은 사고가 아닙니다. 공유하고 원래 앱으로 돌아가는 것이 이 앱의
 * 정상적인 사용 흐름이라 자주 일어나고, 그때마다 원가가 계산보다 위로 샙니다.
 *
 * 이름표가 있으면 서버가 "아까 그 요청"을 알아보고 저장해둔 결과를 그대로
 * 돌려줍니다. 사용자 눈에는 더 빨리 끝난 것으로만 보입니다.
 *
 * 값이 남아 있다는 것은 '아직 끝나지 않은 정리가 있다'는 뜻입니다. 끝나면 비웁니다.
 */
export function createEnrichRequestId() {
  return `enr_${Date.now()}_${Math.random().toString(36).slice(2, 10)}`;
}

/** 정리를 거는 쪽이 정하는 것. 지금은 '끊긴 것을 이어서 하는가' 하나뿐입니다. */
export type EnrichOptions = {
  /**
   * 앱이 죽어 끊겼던 정리를 이어서 도는 경우입니다. 이때만 이름표를 물려받습니다.
   *
   * 나머지는 전부 새 이름표를 받습니다. 조각을 붙였거나 사용자가 재분석을 누른
   * 경우는 넣는 재료가 달라진 것이라, 물려받으면 서버가 재료가 바뀐 줄 모르고
   * 예전 결과를 돌려줍니다.
   */
  resumeRequestId?: boolean;
};

/**
 * 서버가 그 이름표로 받아둔 결과를 이미 비웠다는 뜻입니다.
 *
 * 보관 기간이 지난 이름표로는 몇 번을 물어도 같은 답만 옵니다. 그대로 두면 그 저장물은
 * 영영 정리되지 않으므로, 새 이름표를 받아 한 번 더 걸어야 합니다. 실패와 구별해야
 * 하는 이유가 이것이라, 사유 문자열이 아니라 따로 둡니다.
 */
export class EnrichRequestExpiredError extends Error {
  constructor() {
    super('정리 요청의 보관 기간이 지났습니다. 새 요청으로 다시 겁니다.');
    this.name = 'EnrichRequestExpiredError';
  }
}
